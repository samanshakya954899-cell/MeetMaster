const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  fs.mkdirSync('artifacts', {recursive: true});
  const browser = await chromium.launch({channel:'msedge',headless:true});
  const page = await browser.newPage({viewport:{width:1536,height:900}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  let recovery=false;
  let calls=[];
  const realState = await (await page.request.get('http://127.0.0.1:8787/api/state')).json();
  await page.route('**/api/state', route=>route.fulfill({json:{...realState,config:{...realState.config,signed_in:recovery,password_recovery:recovery}}}));
  await page.route('**/api/auth/**', async route=>{
    const path=new URL(route.request().url()).pathname;
    const data=route.request().postDataJSON();
    calls.push({path,data});
    if(path.endsWith('/login')) return route.fulfill({status:401,json:{error:'Email or password is incorrect.'}});
    if(path.endsWith('/signup')) return route.fulfill({json:{message:'Check your email for confirmation.',verification_required:true}});
    if(path.endsWith('/verify')) recovery=data.purpose==='recovery';
    if(path.endsWith('/password')) recovery=false;
    await route.fulfill({json:{message:'Test response'}});
  });
  await page.goto('http://127.0.0.1:8787/');
  await page.getByRole('heading',{name:'Welcome back to Meet Master'}).waitFor();
  assert.equal(await page.locator('.sidebar').isVisible(),false);
  assert.equal(await page.getByRole('button',{name:'Continue with Google'}).isEnabled(),false);
  await page.screenshot({path:'artifacts/login-email.png',fullPage:true});
  await page.getByLabel('Email',{exact:true}).fill('person@example.com');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByLabel('Password',{exact:true}).waitFor();
  assert.equal(calls.length,0,'Entering email must not send an OTP');
  await page.getByLabel('Password',{exact:true}).fill('password123');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.locator('#toast').filter({hasText:'incorrect'}).waitFor();
  assert.equal(calls.at(-1).path,'/api/auth/login');
  await page.getByRole('button',{name:'Login with OTP',exact:true}).click();
  await page.getByLabel('Verification code').waitFor();
  assert.equal(calls.length,2);
  assert.equal(calls.at(-1).path,'/api/auth/code');
  assert.equal(calls.at(-1).data.email,'person@example.com');
  assert.equal(calls.at(-1).data.purpose,'login');
  assert.equal(await page.locator('[name=password]').count(),0);
  await page.getByRole('button',{name:'Back to sign in'}).click();
  await page.getByRole('button',{name:'Don’t have an account? Sign up'}).click();
  await page.getByLabel('Full name').fill('Test Person');
  await page.getByLabel('Create password',{exact:true}).fill('password123');
  await page.screenshot({path:'artifacts/login-signup.png',fullPage:true});
  await page.getByRole('button',{name:'Send verification code'}).click();
  await page.getByLabel('Verification code').waitFor();
  assert.equal(calls.at(-1).data.company,undefined);
  assert.equal(calls.at(-1).data.name,'Test Person');
  await page.getByRole('button',{name:'Back to sign in'}).click();
  await page.getByRole('button',{name:'Login with OTP'}).click();
  await page.getByLabel('Verification code').waitFor();
  assert.equal(calls.at(-1).data.purpose,'login');
  await page.getByLabel('Verification code').fill('123456');
  await page.getByRole('button',{name:'Verify and continue'}).click();
  await page.getByRole('heading',{name:'Welcome back to Meet Master'}).waitFor();
  assert.equal(calls.at(-1).path,'/api/auth/verify');
  assert.equal(calls.at(-1).data.purpose,'login');
  await page.getByLabel('Email',{exact:true}).fill('person@example.com');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('button',{name:'Change',exact:true}).click();
  assert.equal(await page.getByLabel('Email',{exact:true}).inputValue(),'person@example.com');
  for(const width of [390,768]){
    await page.setViewportSize({width,height:844});
    await page.screenshot({path:`artifacts/login-mobile-${width}.png`,fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  }
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Auth flow passed: direct email OTP, signup metadata, verification, change email and mobile layouts. External auth responses were mocked; no emails sent.');
})().catch(error=>{console.error(error);process.exit(1);});
